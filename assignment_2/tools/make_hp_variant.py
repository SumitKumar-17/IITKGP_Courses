#!/usr/bin/env python3
"""Derives partB/bench/kvstore_hp.cpp (hazard pointers) from partB/kvstore.cpp (epochs).

The variant exists only to compare the two reclamation schemes on identical code, so it
is generated rather than maintained by hand: run this after changing partB/kvstore.cpp.
"""
s = open("partB/kvstore.cpp").read()


def rep(a, b):
    global s
    assert a in s, a
    s = s.replace(a, b, 1)


rep('// kvstore.cpp (Part B)\n#include "kvstore.h"',
    '// kvstore_hp.cpp: kvstore.cpp with hazard pointers in place of epochs, built only to\n'
    '// compare the two schemes on identical code (see README.md). Differences are the\n'
    '// ReadGuard, the Version sequence number, and how the reclamation floor is found.\n'
    '// Generated by tools/make_hp_variant.py; do not edit by hand.\n#include "../kvstore.h"')
a = s.index("// Announces the reader.")
b = s.index("// -------------------------------------------------------------- read side")
s = s[:a] + '''// Hazard pointer: the reader publishes the Version it is about to use and
// re-checks that it is still current, which needs a second load.
template <class V>
struct ReadGuard {
    EpochSlot* s;
    const V* v;
    explicit ReadGuard(const std::atomic<V*>& cur) : s(my_slot()) {
        for (;;) {
            V* p = cur.load(std::memory_order_seq_cst);
            s->epoch.store(reinterpret_cast<uint64_t>(p), std::memory_order_seq_cst);
            if (cur.load(std::memory_order_seq_cst) == p) { v = p; return; }
        }
    }
    ~ReadGuard() { s->epoch.store(kIdle, std::memory_order_release); }
};

// Oldest version any reader still holds. Garbage from that version on stays.
template <class V>
uint64_t min_protected_seq() {
    std::atomic_thread_fence(std::memory_order_seq_cst);
    uint64_t m = kIdle;
    int hwm = g_slot_hwm.load(std::memory_order_acquire);
    for (int i = 0; i < hwm; i++) {
        uint64_t e = g_slots[i].epoch.load(std::memory_order_acquire);
        if (e == kIdle) continue;
        uint64_t seq = reinterpret_cast<const V*>(e)->seq;
        if (seq < m) m = seq;
    }
    return m;
}

''' + s[b:]
rep("struct KVStore::Version {\n    uintptr_t root;\n    long count;\n};",
    "struct KVStore::Version {\n    uintptr_t root;\n    long count;\n    uint64_t seq;\n};")
rep("T* alloc_version(uintptr_t root, long count) {", "T* alloc_version(uintptr_t root, long count, uint64_t seq) {")
rep("    v->count = count;\n    return v;", "    v->count = count;\n    v->seq = seq;\n    return v;")
rep("alloc_version<Version>(0, 0)", "alloc_version<Version>(0, 0, 0)")
rep("alloc_version<Version>(root, old->count + delta)", "alloc_version<Version>(root, old->count + delta, old->seq + 1)")
rep("    ReadGuard guard;\n    const Version* v = current_.load(std::memory_order_seq_cst);\n    const Val* val",
    "    ReadGuard<Version> guard(current_);\n    const Version* v = guard.v;\n    const Val* val")
rep("    ReadGuard guard;\n    return static_cast<size_t>(current_.load(std::memory_order_seq_cst)->count);",
    "    ReadGuard<Version> guard(current_);\n    return static_cast<size_t>(guard.v->count);")
rep("    g->epoch = g_epoch.load(std::memory_order_relaxed);", "    g->epoch = old->seq;")
rep("    g_epoch.fetch_add(1, std::memory_order_acq_rel);\n", "")
rep("uint64_t floor = min_active_epoch();", "uint64_t floor = min_protected_seq<Version>();")
open("partB/bench/kvstore_hp.cpp", "w").write(s)
